# 内部风味覆盖的核心题材（应与 CORE_GENRES 完全一致）
INTERNAL_FLAVOR_GENRES = list(INTERNAL_FLAVORS.keys())


def get_block(dimension: str, option: str) -> dict | None:
    """按维度 + 选项名取积木块；不存在返回 None。"""
    blocks = DIMENSION_BLOCKS.get(dimension)
    if not blocks:
        return None
    return blocks.get(option)


def roll_internal_flavor(config: dict | None) -> dict:
    """
    随机为 config 的核心题材掷一组内部细粒度风味，写回 config["internal_flavor"]。

    - 只从 INTERNAL_FLAVORS[core_genre] 中抽取，绝不越界到其它题材；
    - 随机选 1 个（约 50%）或组合 2-3 个（约 50%），单次不重复；
    - 若 core_genre 缺失或该题材未收录风味，internal_flavor 置为空列表；
    - 每个项目调用一次即可保证全书风味一致；可再次调用以「重新掷风味」。
    """
    if config is None:
        return {}
    genre = config.get("core_genre")
    # I3：类型防御——genre 非字符串（缺失/None/不可哈希类型）时不得进入 INTERNAL_FLAVORS.get，
    # 否则 unhashable 类型会抛 TypeError。统一置为空列表并返回。
    if not isinstance(genre, str):
        config["internal_flavor"] = []
        return config
    flavors = INTERNAL_FLAVORS.get(genre)
    if not flavors:
        config["internal_flavor"] = []
        return config
    keys = list(flavors.keys())
    count = random.choices((1, 2, 3), weights=(50, 30, 20))[0]
    count = min(count, len(keys))
    config["internal_flavor"] = random.sample(keys, count)
    return config


def _render_internal_flavor(config: dict) -> str:
    """把 config["internal_flavor"] 渲染成「内部风味」上下文段；无风味则返回空串。"""
    flavor_keys = config.get("internal_flavor")
    if isinstance(flavor_keys, str):  # 防御：老数据可能存成单个字符串
        flavor_keys = [flavor_keys]
    if not flavor_keys:
        return ""
    genre = config.get("core_genre")
    flavor_blocks = INTERNAL_FLAVORS.get(genre, {}) if isinstance(genre, str) else {}
    lines = []
    for key in flavor_keys:
        if not isinstance(key, str) or not key.strip():
            continue
        block = flavor_blocks.get(key)
        if block:
            label = block.get("label", key)
            fragment = str(block.get("prompt_fragment", "")).strip()
            if fragment:
                lines.append(f"· {label}：{fragment}")
                continue
        # 未知风味/自由文本，降级原文直述，避免丢失信息
        lines.append(f"· {key.strip()}")
    if not lines:
        return ""
    return "【内部风味】\n" + "\n".join(lines)


def _shorten_fragment(fragment: str, max_sentences: int = 2) -> str:
    """把 prompt_fragment 精简为前 max_sentences 句，控制多选维度拼接时的篇幅。

    多选维度每项只取核心内容（氛围/卖点概述 1-2 句），避免多项全量拼接导致上下文臃肿。
    """
    text = fragment.strip()
    if not text:
        return ""
    pieces = re.split(r"(?<=[。！？])", text)
    pieces = [p.strip() for p in pieces if p.strip()]
    if len(pieces) <= max_sentences:
        return text
    return "".join(pieces[:max_sentences])


def _render_multi_select(dim: str, values: list) -> str:
    """渲染多选维度（background/hook）为一段「写作上下文」。

    逐项查积木块：命中项注入各 prompt_fragment 的核心内容（精简到 1-2 句）；
    未知项（前端新选项/自由文本）降级为原文直述，避免丢失信息与崩溃。
    """
    lines = []
    for value in values:
        if not isinstance(value, str) or not value.strip():
            continue
        block = get_block(dim, value)
        if block is not None:
            label = block.get("label", value)
            core = _shorten_fragment(str(block.get("prompt_fragment", "")))
            lines.append(f"· {label}：{core}" if core else f"· {label}")
        else:
            lines.append(f"· {value.strip()}")
    if not lines:
        return ""
    return f"【{DIMENSION_LABELS[dim]}】\n" + "\n".join(lines)


# 用户自定义要求（writing_config.custom）5 字段的显示名
CUSTOM_FIELD_LABELS = {
    "core_selling_point": "核心卖点要求",
    "unique_setting": "独特设定",
    "character_req": "角色要求",
    "avoid": "需避免",
    "free_note": "补充说明",
}


def _render_custom_requirements(config: dict) -> str:
    """把 config["custom"] 的 5 个自定义字段格式化为「用户自定义要求」上下文段。

    只输出有值（非空白字符串）的字段；全部为空或 custom 缺失时返回空串，不出现该段。
    """
    custom = config.get("custom")
    if not isinstance(custom, dict):
        return ""
    lines = []
    for key, label in CUSTOM_FIELD_LABELS.items():
        value = custom.get(key)
        if isinstance(value, str) and value.strip():
            lines.append(f"· {label}：{value.strip()}")
    if not lines:
        return ""
    return "【用户自定义要求】\n" + "\n".join(lines)


def build_context(config: dict | None) -> str:
    """
    把 config 各维度的 prompt_fragment 拼成一段「写作上下文」文本。

    config 形如：
      {"core_genre": "玄幻", "background": ["宗门林立", "大陆争霸"], "hook": ["金手指系统"], ...}
    多选维度（background/hook）为数组时逐项查块、注入各 prompt_fragment 的核心内容；
    未知维度 / 未知选项会被忽略或降级为原文直述；用户自定义要求（writing_config.custom
    的 5 个字段）有值时以【用户自定义要求】段拼接到末尾；剧情走向不在此处拼接
    （剧情走向由创作意图环节单独高优先注入，保持职责正交）。
    """
    if not config:
        return ""
    sections = []
    for dim in DIMENSION_ORDER:
        option = config.get(dim)
        if not option:
            continue
        if isinstance(option, list):
            section = _render_multi_select(dim, option)
            if section:
                sections.append(section)
        else:
            block = get_block(dim, option)
            if block is None:
                # 前端可能传入新选项或自由文本，降级为原文直述，避免丢失信息
                fragment = str(option).strip()
                if not fragment:
                    continue
                sections.append(f"【{DIMENSION_LABELS[dim]}】\n{fragment}")
            else:
                sections.append(
                    f"【{DIMENSION_LABELS[dim]}·{block['label']}】\n{block['prompt_fragment'].strip()}"
                )
        # 内部细粒度风味紧跟在核心题材之后，作为题材的细化
        if dim == "core_genre":
            flavor_section = _render_internal_flavor(config)
            if flavor_section:
                sections.append(flavor_section)
    # I2：用户自定义要求（custom 5 字段）拼到上下文末尾，有值才出现
    custom_section = _render_custom_requirements(config)
    if custom_section:
        sections.append(custom_section)
    return "\n\n".join(sections)
