# structure_guidance.py
# -*- coding: utf-8 -*-
"""
叙事结构条件化指引（V3 P3-A 去危机化）。

把「危机形状」硬规则从各生成 prompt 中抽离为条件占位符分片：
- 危机驱动结构（升级打怪 / 三幕经典 / 倒叙钩子 / 单元剧快节奏 / 长线连载）
  沿用现状文本，作为默认基线（与改造前行为一致）。
- 平静结构（日常流 / 群像交织）替换为平静/正反馈分片：
  不强制异常征兆、打破平衡、悬念曲线，保留人物魅力 + 生活切片 + 正反馈。

关键接口：
- build_structure_guidance(structure: str | None) -> dict
  返回 {seed, character, world, first_chapter, chapter, blueprint} 六个分片。
  未知 / 缺省 structure → 危机基线（不报错，行为与改造前一致）。
"""

# 危机驱动结构：保留现有关卡（升级打怪 / 三幕经典 / 倒叙钩子 / 单元剧快节奏 / 长线连载）
CRISIS_STRUCTURES = {"升级打怪", "三幕经典", "倒叙钩子", "单元剧快节奏", "长线连载"}
# 平静结构：不强制危机硬规则
CALM_STRUCTURES = {"日常流", "群像交织"}

# 危机基线分片（= prompts.py 改造前的现状文本，逐字保留）
_CRISIS_SEED = (
    "请用单句公式概括故事本质，例如："
    "\"当[主角]遭遇[核心事件]，必须[关键行动]，否则[灾难后果]；与此同时，[隐藏的更大危机]正在发酵。\"\n"
    "要求：体现人物核心驱动力，暗示世界观关键矛盾，使用 25-100 字精准表达。"
)
_CRISIS_CHARACTER = (
    "角色弧线设计：初始状态 → 触发事件 → 认知失调 → 蜕变节点 → 最终状态。\n"
    "关系冲突网：与其他角色的关系或对立点，与至少两个其他角色的价值观冲突，"
    "一个合作纽带，一个隐藏的背叛可能性。"
)
_CRISIS_WORLD = (
    "2. 社会维度：\n"
    "- 权力结构断层线（可引发冲突的阶层/种族/组织矛盾）\n"
    "- 文化禁忌（可被打破的禁忌及其后果）\n"
    "- 经济命脉（资源争夺焦点）"
)
_CRISIS_FIRST_CHAPTER = (
    "1. 开篇必须出现贯穿全书的视觉符号或核心意象。\n"
    "2. 展示主角的日常状态，同时埋下至少 2 个异常征兆。\n"
    "3. 本章结束前必须发生一个打破平衡的事件。"
)
_CRISIS_CHAPTER = (
    "1. 开篇必须与前文形成情感或情节上的张力对比（紧张→缓冲，或缓冲→紧张）。\n"
    "2. 至少推动 1 条主线或暗线的发展。\n"
    "3. 展现至少 1 个角色的变化或新信息揭示。"
)
_CRISIS_BLUEPRINT = (
    "1. 章节集群划分：按剧情自然推进划分章节集群，使每段节奏有起有落、张弛有度；"
    "关键转折章可预留多视角铺垫。\n"
    "2. 每章需明确：章节定位（角色/事件/主题等）、核心悬念类型（信息差/道德困境/"
    "时间压力等）、情感基调迁移（如从怀疑→恐惧→决绝）、伏笔操作（埋设/强化/回收）、"
    "悬念密度（紧凑/渐进/爆发等）。"
)

# 平静结构分片（日常流 / 群像交织）
_CALM_SEED = (
    "请用一句平实的话概括故事本质：主角身处何种处境、想要什么、将面对什么选择；\n"
    "不要求设计\"灾难后果\"或\"隐藏更大危机\"，但要体现人物核心驱动力，使用 25-100 字精准表达。"
)
_CALM_CHARACTER = (
    "角色弧线设计：初始状态 → 发展变化 → 最终状态（不必强制经历\"触发事件\"与\"认知失调\"，"
    "变化可以温和渐进）。\n"
    "关系网：与其他角色的关系或对立点，至少一个合作或羁绊纽带；不强求价值观冲突与隐藏背叛，"
    "关系可以有日常的温度与张力，服务于人物的成长与情感。"
)
_CALM_WORLD = (
    "2. 社会维度：\n"
    "- 生活方式与风俗习惯（人物的日常空间、衣食住行）\n"
    "- 社会关系网络（家族、邻里、师友、同事之间的连接）\n"
    "- 生活环境与稳定秩序（人物栖身的场所与常驻状态，不必为冲突设计断层线）"
)
_CALM_FIRST_CHAPTER = (
    "1. 开篇自然进入主角的生活：展现人物魅力与生活切片，不强求异常征兆。\n"
    "2. 可安排一个轻微的变化（一次相遇、一个决定、一件小事引发的涟漪），不必打破平衡。\n"
    "3. 画面感与生活气息要足，让读者愿意住进这个世界；角色设定须与【角色状态】一致。"
)
_CALM_CHAPTER = (
    "1. 开篇自然衔接前文，不要求张力对比。\n"
    "2. 不强求每章都推动主线，但要有一个值得一读的变化（情绪、关系或处境的推进）。\n"
    "3. 本章可以以人物情绪、关系变化、日常细节的积累收束，不必以冲突收尾。"
)
_CALM_BLUEPRINT = (
    "1. 章节集群划分：按剧情自然推进划分章节集群，使每段节奏张弛有度；"
    "不强求每章都有悬念曲线，允许平和舒缓的过渡章节。\n"
    "2. 每章需明确：章节定位（角色/事件/主题等）、本章变化（人物情绪/关系/处境）、"
    "情感基调（可平和温暖）、可选的伏笔操作（埋设/推进/回收）。"
)


def _crisis_guidance() -> dict:
    return {
        "seed": _CRISIS_SEED,
        "character": _CRISIS_CHARACTER,
        "world": _CRISIS_WORLD,
        "first_chapter": _CRISIS_FIRST_CHAPTER,
        "chapter": _CRISIS_CHAPTER,
        "blueprint": _CRISIS_BLUEPRINT,
    }


def _calm_guidance() -> dict:
    return {
        "seed": _CALM_SEED,
        "character": _CALM_CHARACTER,
        "world": _CALM_WORLD,
        "first_chapter": _CALM_FIRST_CHAPTER,
        "chapter": _CALM_CHAPTER,
        "blueprint": _CALM_BLUEPRINT,
    }


def build_structure_guidance(structure: str | None) -> dict:
    """按 structure 返回六个分片；未知 / 缺省回退危机基线（不报错）。"""
    if structure is not None and structure.strip() in CALM_STRUCTURES:
        return _calm_guidance()
    return _crisis_guidance()
